/// Represents the standardized stroke widths used throughout the app's UI,
/// ensuring a consistent visual appearance for borders, lines, and other
/// stroked elements.
abstract class AppStroke {
  /// Specifies a thin stroke width, equivalent to 1 logical pixel.
  /// This width is often used for subtle borders or light separations.
  static const double thin = 1;

  /// Specifies a thicker stroke width, equivalent to 2 logical pixels.
  /// Suitable for more prominent borders or elements that require clear
  /// distinction.
  static const double thick = 2;
}
